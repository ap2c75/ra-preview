const norm = s => String(s ?? '').replace(/\s+/g, '').toLowerCase();

/* 🔴 배열 순서대로 보면 안 된다 — 실측으로 오답이 났다.
      "안마의자 얼마예요" 가 「소파·가구」로 갔다. 문장의 **「의자」**가 먼저 걸렸기 때문이다.
      고객이 안마의자를 물었는데 소파 가격을 말하는 셈이다.
   🔑 **긴 별칭부터** 본다. 「안마의자」(4자)가 「의자」(2자)를 이긴다. */
/* 🔴 별칭은 문자열이거나 `{ a, not }` 이다.
      `not` 은 **그 별칭을 삼키는 더 긴 말**이다 — 「아이스」를 「아이스크림」이 삼킨다.
      주석에 「한글은 조사가 붙어 경계가 없으므로 그대로 포함 검사한다 — 거기선 이 문제가
      안 난다」고 적혀 있었는데 **실측이 그걸 뒤집었다**(2026-09-10):
        · 아이스크림 제조기·자판기 **25종이 정수기**로 분류돼 있었다(혜택표 실측)
        · 뉴스에서 「1인 가구」→소파·가구, 「모니터링」→PC, 「슬립맥싱」→매트리스
      라틴 문자는 낱말 경계로 풀었지만 한글은 경계가 없으므로 **덫을 이름으로 적는다.** */
const FLAT = TAXONOMY
  .flatMap(t => t.aliases.map(x => {
    const a = typeof x === 'string' ? x : x.a;
    return { a: norm(a), len: a.length, name: t.name,
             not: (typeof x === 'string' ? [] : (x.not ?? [])).map(norm) };
  }))
  .sort((x, y) => y.len - x.len);

/* 덫을 지우고 나서도 별칭이 남아 있으면 진짜로 있는 것이다 */
const hasAlias = (hay, f) => {
  const clean = f.not.length ? f.not.reduce((s, n) => s.split(n).join(' '), hay) : hay;
  return clean.includes(f.a);
};

/* 🔴 라틴 문자 별칭은 **낱말 경계**를 요구한다.
      `pc` 가 「S**PC** GFS」에 걸려 「SPC GFS, 상주 곶감 판로 확대」가
      PC·사무기기로 분류됐다(다뿌려 뉴스 제목 실측 2026-09-09).
      한글은 조사가 붙어 경계가 없으므로 그대로 포함 검사한다 — 거기선 이 문제가 안 난다. */
const LATIN = /^[a-z0-9]+$/;
const boundaryRe = a => new RegExp(`(^|[^a-z0-9])${a}($|[^a-z0-9])`);

/** 원문 분류·제품명에서 표준 품목을 고른다. 못 고르면 null. */
export function toCategory(...raw) {
  const hay = norm(raw.filter(Boolean).join(' '));
  if (!hay) return null;
  return FLAT.find(f => (LATIN.test(f.a) ? boundaryRe(f.a).test(hay) : hasAlias(hay, f)))?.name ?? null;
}

/** 사람이 말한 문장에서 품목을 찾는다 (자유 질문용) */
export const categoryFromText = text => toCategory(text);

/** 표준 품목 순서대로 정렬 — 화면 순서를 사전이 정한다 */
export function sortCategories(names) {
  const order = new Map(TAXONOMY.map((t, i) => [t.name, i]));
  return [...names].sort((a, b) => (order.get(a) ?? 99) - (order.get(b) ?? 99));
}
